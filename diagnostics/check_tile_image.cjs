const assert = require('node:assert/strict');
const fs = require('node:fs');
const {chromium} = require('../babylon/node_modules/@playwright/test');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--use-angle=swiftshader','--enable-webgl','--ignore-gpu-blocklist']});
 try {
  const page=await browser.newPage({viewport:{width:1600,height:1100}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8514');
  await page.locator('.hexsphere-plot[data-ready=true] canvas').first().waitFor({timeout:60000});
  await page.getByText('PictureSphere',{exact:true}).click();
  const uploader=()=>page.locator('input[type=file][accept*=".png"]');
  await uploader().waitFor({state:'attached'});
  await page.waitForFunction(()=>document.querySelector('.hexsphere-plot')?.data?.[0].facecolor?.length>0);
  const read=()=>page.locator('.hexsphere-plot').evaluate(p=>({traces:p.data.map(t=>({name:t.name,x:t.x,y:t.y,z:t.z,facecolor:t.facecolor})),camera:p._fullLayout.scene.camera}));
  const original=await read();
  await uploader().setInputFiles('diagnostics/tile_image_test.png');
  await page.getByText('Saved image: tile_image_test.png',{exact:true}).waitFor();
  await page.waitForFunction(()=>document.querySelector('.hexsphere-plot')?.data?.some(t=>t.name==='Tile images'));
  const image=await read();
  assert.deepEqual(image.traces[0].facecolor,original.traces[0].facecolor);
  assert(new Set(image.traces.find(t=>t.name==='Tile images').facecolor).size>3);
  await page.locator('.hexsphere-plot').evaluate(p=>{
   const t=p.data.find(t=>t.name==='Tile images');
   const center=['x','y','z'].map(a=>t[a].reduce((x,y)=>x+y,0)/t[a].length);
   const d=Math.hypot(...center);
   return Plotly.relayout(p,{'scene.camera.eye':{x:center[0]/d*1.8,y:center[1]/d*1.8,z:center[2]/d*1.8}});
  });
  const character=page.locator('.st-key-picture_sphere_paint_character input');
  await character.fill('ß');await character.press('Enter');
  await page.getByRole('button',{name:'Paint Selected Tile',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.hexsphere-plot')?.data?.some(t=>t.name==='Tile Labels'));
  const withGlyph=await read();
  await page.locator('.hexsphere-plot').screenshot({path:'diagnostics/tile_image_overlay.png'});
  await page.getByText('Show tile names',{exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.hexsphere-plot')?.data?.some(t=>t.name==='Tile names'));
  const named=await read();
  assert.deepEqual(named.traces.find(t=>t.name==='Tile images'),withGlyph.traces.find(t=>t.name==='Tile images'));
  await page.getByText('Show tile names',{exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.hexsphere-plot')?.data?.some(t=>t.name==='Tile Labels'));
  const restored=await read();
  assert.deepEqual(restored.traces,withGlyph.traces);
  assert.deepEqual(restored.camera,withGlyph.camera);
  const slider=page.locator('.st-key-picture_sphere_image_scale').getByRole('slider');
  const sliderValue=()=>slider.evaluate(el=>Number(el.value ?? el.getAttribute('aria-valuenow')));
  assert.equal(await sliderValue(),1);
  await slider.focus();await page.keyboard.press('Home');await page.keyboard.press('ArrowRight');await page.keyboard.press('ArrowRight');
  await page.waitForFunction(()=>{const el=document.querySelector('.st-key-picture_sphere_image_scale input[type=range], .st-key-picture_sphere_image_scale [role=slider]');return el && Number(el.value ?? el.getAttribute('aria-valuenow'))===0.3;});
  await page.waitForFunction(()=>{
   const t=document.querySelector('.hexsphere-plot')?.data?.find(t=>t.name==='Tile images');
   return t && Math.max(...t.x)-Math.min(...t.x)<0.5;
  });
  const small=await read();
  assert.deepEqual(small.traces.find(t=>t.name==='Tile Labels'),withGlyph.traces.find(t=>t.name==='Tile Labels'));
  await page.locator('.hexsphere-plot').screenshot({path:'diagnostics/tile_image_scaled.png'});
  const target=page.locator('.st-key-picture_sphere_target_tile_label input');
  await target.click();await page.getByRole('option',{name:'R1-S1',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.st-key-picture_sphere_paint_character input')?.value==='');
  assert.equal(await sliderValue(),1);
  assert.deepEqual((await read()).traces.find(t=>t.name==='Tile images'),small.traces.find(t=>t.name==='Tile images'));
  await target.click();await page.getByRole('option',{name:'Anchor-0',exact:true}).click();
  await page.getByText('Saved image: tile_image_test.png',{exact:true}).waitFor();
  assert.equal(await sliderValue(),0.3);
  await page.getByRole('button',{name:'Remove focused tile image',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('.hexsphere-plot')?.data?.some(t=>t.name==='Tile images'));
  const removed=await read();
  assert.deepEqual(removed.traces.find(t=>t.name==='Tile Labels'),withGlyph.traces.find(t=>t.name==='Tile Labels'));
  assert.deepEqual(removed.traces[0].facecolor,original.traces[0].facecolor);
  assert.deepEqual(errors,[]);
  const result={actual_upload:true,image_detail:true,unicode_above_image:true,names_restore_image:true,scale_default:1,scale_changed:0.3,focus_preserves_image:true,removal_restores_color:true,errors};
  fs.writeFileSync('diagnostics/tile_image_results.json',JSON.stringify(result,null,2));console.log(result);
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
